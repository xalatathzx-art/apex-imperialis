/**
 * Поставить русские описания поверх тех, что дописали другие модули.
 *
 * Действие, которого в конфиге нет (модуль с ним выключен), пропускаем молча —
 * это не ошибка, а другой набор включённых модулей.
 */
export function registerVehicleActionRules() {
  if (game.i18n.lang !== "ru") return;

  const actions = game.impmal?.config?.vehicleActions;
  if (!actions) return;

  let applied = 0;
  for (const [key, description] of Object.entries(VEHICLE_ACTION_DESCRIPTIONS)) {
    if (!actions[key]) continue;
    actions[key].description = description;
    applied++;
  }

  console.log(`${MODULE_ID} | ${applied} vehicle action rules translated`);
}
