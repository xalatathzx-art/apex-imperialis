/**
 * Мехадендриты — DoomBC стр. 277–278, Адептус Механикус.
 *
 * Twelve mehadendrites, all mounted on the Кибер-Мантия rather than replacing
 * a body part outright, and every one of them is built around a full weapon
 * or tool profile (Rng/Dmg/Pen/Свойства), a combat-mode choice, and a strength
 * rating of its OWN independent of the wearer's — none of which the implant
 * mechanics constructor has a path for. `targets.js` reaches the actor's own
 * characteristics and skills; it cannot create a weapon item with its own
 * profile, and a mehadendrite's whole point is that profile. Every entry in
 * this file is therefore prose, same as the bionic weapon-arm variations in
 * Task 13's file.
 *
 * The one plain, unconditional number here — Мехатендрил's +5 per additional
 * unit to Craft tests — would need to sum ACROSS every mehatendril the
 * character owns, which is a per-owner count `mechanics` cannot see (an
 * item's own entries know nothing about how many siblings are installed). It
 * stays prose as well, and is called out explicitly rather than silently
 * dropped.
 */

