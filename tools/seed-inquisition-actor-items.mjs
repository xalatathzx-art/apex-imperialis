import fs from "node:fs";
import path from "node:path";
import { readPack, partition } from "./lib/level.mjs";

const root = path.resolve(import.meta.dirname, "..");
const copied = path.join(root, "tmp", "inquisition-packs-f3f0cbe940194fb3b5146cce9f500140");
const sourceDir = path.join(root, "src", "compendium");
const output = path.join(sourceDir, "impmal-inquisition.actors.reused-items.mjs");
const index = JSON.parse(fs.readFileSync(path.join(sourceDir, "packs-index.json"), "utf8"));

const translations = new Map();
const priority = collection => collection === "impmal-core.items" ? 3 : collection === "impmal-inquisition.items" ? 2 : 1;
for (const [collection, pack] of Object.entries(index)) {
  if (pack.documentName !== "Item") continue;
  const builtPath = path.join(root, "compendium", collection + ".json");
  if (!fs.existsSync(builtPath)) continue;
  const built = JSON.parse(fs.readFileSync(builtPath, "utf8")).entries;
  for (const [id, translated] of Object.entries(built)) {
    const original = pack.entries[id];
    if (!original || !translated.name) continue;
    const key = original.type + "\0" + original.name;
    const previous = translations.get(key);
    if (!previous || priority(collection) > previous.priority) {
      translations.set(key, { name: translated.name, priority: priority(collection) });
    }
  }
}

// Descriptions from this Guide are reused only for byte-identical embedded copies.
const itemPack = partition(await readPack(path.join(copied, "items"))).primary;
const builtItems = JSON.parse(fs.readFileSync(path.join(root, "compendium", "impmal-inquisition.items.json"), "utf8")).entries;
for (const item of itemPack) {
  const translated = builtItems[item._id];
  if (!translated?.name) continue;
  const key = item.type + "\0" + item.name;
  const previous = translations.get(key);
  translations.set(key, {
    name: previous?.name ?? translated.name,
    priority: Math.max(previous?.priority ?? 0, 2),
    description: translated.description,
    originalDescription: item.system?.notes?.player ?? ""
  });
}

const actors = partition(await readPack(path.join(copied, "actors")));
const entries = {};
let names = 0;
let descriptions = 0;
for (const actor of actors.primary) {
  const items = {};
  for (const [key, item] of Object.entries(actors.embedded)) {
    if (!key.startsWith("!actors.items!" + actor._id + ".")) continue;
    const translated = translations.get(item.type + "\0" + item.name);
    if (!translated) continue;
    const entry = { name: translated.name };
    names++;
    const originalDescription = item.system?.notes?.player ?? "";
    if (translated.description != null && translated.originalDescription === originalDescription) {
      entry.description = translated.description;
      descriptions++;
    }
    items[item.name] = entry;
  }
  if (Object.keys(items).length) entries[actor._id] = { items };
}

const js = "// Generated by tools/seed-inquisition-actor-items.mjs.\n" +
  "// Re-run after translating more source items.\n" +
  "export const label = \"Актёры (Руководство Инквизиции)\";\n" +
  "export const entries = " + JSON.stringify(entries, null, 2) + ";\n";
fs.writeFileSync(output, js);
console.log(names + " embedded item names reused; " + descriptions + " identical descriptions reused");
