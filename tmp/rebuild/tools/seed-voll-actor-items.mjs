/** Reuse only already approved Navis translations in Voll actors. */
import fs from "node:fs";
import path from "node:path";
import { readPack, partition } from "./lib/level.mjs";
import { VOLL_ITEMS } from "../src/compendium/shared/voll-items.mjs";

const root = path.resolve(import.meta.dirname, "..");
const copied = path.join(root, "tmp", "voll-packs-c07370d86763445e9eab79b64def675a");
const sourceDir = path.join(root, "src", "compendium");
const output = path.join(sourceDir, "impmal-voll.actors.reused-items.mjs");
const index = JSON.parse(fs.readFileSync(path.join(sourceDir, "packs-index.json"), "utf8"));
const terms = JSON.parse(fs.readFileSync(path.join(root, "docs", "rules", "ru-terms.json"), "utf8"));
const termByFoldedName = new Map(Object.entries(terms).map(([en, ru]) => [en.trim().toLowerCase(), ru]));
const normalized = text => String(text ?? "").replace(/\s+/g, " ").trim();

const translations = new Map();
const approvedDescriptions = new Map();
for (const [collection, pack] of Object.entries(index)) {
  if (pack.documentName !== "Item") continue;
  const builtPath = path.join(root, "compendium", `${collection}.json`);
  if (!fs.existsSync(builtPath)) continue;
  const built = JSON.parse(fs.readFileSync(builtPath, "utf8")).entries;
  for (const [id, translated] of Object.entries(built)) {
    const original = pack.entries[id];
    if (!original || !translated.name) continue;
    translations.set(`${original.type}\0${original.name}`, translated);
  }
}

for (const [packPath, collection] of [
  [path.join(root, "tmp", "packs", "items-copy"), "impmal-core.items"],
  [path.join(root, "tmp", "inquisition-packs-f3f0cbe940194fb3b5146cce9f500140", "items"), "impmal-inquisition.items"],
  [path.join(root, "tmp", "requisition-items-copy"), "impmal-requisition.items"]
]) {
  if (!fs.existsSync(packPath)) continue;
  const originals = partition(await readPack(packPath)).primary;
  const builtPath = path.join(root, "compendium", `${collection}.json`);
  if (!fs.existsSync(builtPath)) continue;
  const built = JSON.parse(fs.readFileSync(builtPath, "utf8")).entries;
  for (const item of originals) {
    const description = item.system?.notes?.player ?? "";
    const translated = built[item._id];
    if (description && translated?.description) {
      approvedDescriptions.set(`${item.type}\0${item.name}\0${normalized(description)}`, translated.description);
    }
  }
}

const actors = partition(await readPack(path.join(copied, "actors")));
const embedded = new Map(Object.values(actors.embedded).map(item => [item._id, item]));
const entries = {};
let names = 0;

for (const actor of actors.primary) {
  const items = {};
  for (const id of actor.items ?? []) {
    const item = embedded.get(id);
    if (!item) continue;
    const curated = VOLL_ITEMS[item.name];
    const translated = translations.get(`${item.type}\0${item.name}`) ?? curated;
    const term = terms[item.name] ?? termByFoldedName.get(item.name.trim().toLowerCase());
    const name = translated?.name ?? term;
    if (!name) continue;
    const entry = { name };
    if (curated?.description) entry.description = curated.description;
    const description = item.system?.notes?.player ?? "";
    const approved = approvedDescriptions.get(`${item.type}\0${item.name}\0${normalized(description)}`);
    if (approved) entry.description = approved;
    items[item.name] = entry;
    names++;
  }
  if (Object.keys(items).length) entries[actor._id] = { items };
}

fs.writeFileSync(output,
  "// Generated by tools/seed-voll-actor-items.mjs from approved Navis translations.\n" +
  "export const label = \"Актёры (Приключения на Волле)\";\n" +
  `export const entries = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`${names} embedded names reused`);
