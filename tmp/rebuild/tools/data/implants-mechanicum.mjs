/**
 * Кибернетика Механикум — DoomBC стр. 271–276.
 *
 * The book restricts every implant in this file to characters who already
 * carry the Импланты Механикум trait, at most one of each — a gate this
 * pipeline does not enforce (it is a character-creation rule, not a fitting
 * rule the Surgeon window checks) and is instead written into every entry's
 * `rules` text for the GM to read.
 *
 * FOUR SECTIONS, FOUR DIFFERENT RELATIONSHIPS TO `mechanics`
 *
 * Энергосистемы (power systems) are why `kind: "energy"` and Task 12 exist.
 * Мотивные Банки Манипулюс raises the Заряд ceiling by a flat 5 and is
 * authored exactly as the task brief specifies. Every OTHER power system in
 * this section is a RECHARGE method — spend time or food to refill the pool
 * — not a capacity change, and `energy` entries only ever move the ceiling
 * (`energyCapacity()` in resources.js sums them directly). A recharge rate is
 * not a number `mechanics` has anywhere to put, so those stay prose.
 *
 * Технофокусы (tech-focuses) exist to power Техночудеса — this cycle's
 * technomiracles system is out of scope for implants entirely, so every
 * numeric bonus in this section is prose by construction, not by omission.
 *
 * Фреймы (frames) are the one sub-section with real, unconditional
 * characteristic, armour, Wound and Заряд-ceiling numbers, because a frame is
 * a fixed identity rather than a Poor/Good/Best ladder — the book prints ONE
 * set of numbers per frame, so `levels` for a frame only carries a note that
 * quality does not change its effect, and the numbers go straight into
 * `mechanics`.
 *
 * Прочее (miscellaneous) implants overwhelmingly trigger on a spent action
 * with a chosen Заряд cost, which is a live request no different from the
 * bionic arm variations in Task 13's file — none of it is a standing number.
 * The one exception, Heart of Elder Stephanus's flat +2 AP on every location,
 * is unconditional and becomes `armourAll`.
 *
 * This section's two-column source pages interleave items and quality blocks
 * visually; where the extracted text left genuine doubt about which quality
 * block belongs to which implant (mostly in Прочее), the implant was written
 * prose-only rather than risk attaching a number to the wrong item — the
 * same "wrong gate is worse than no gate" rule as everywhere else in this
 * pipeline. Judgment calls are listed in the task report.
 */

