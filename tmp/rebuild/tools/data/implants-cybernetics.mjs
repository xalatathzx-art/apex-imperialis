/**
 * Кибернетика — DoomBC стр. 265–267.
 *
 * Thirty implants, none of them body-part replacements the way bionics are:
 * these bolt utility, armour and control systems onto a body that is mostly
 * still flesh. Most of what the book grants here is either purely narrative
 * (an implant that works exactly like an item already on the sheet), tied to
 * a named hand or a named machine ("this hand", "the connected device"), or a
 * state the schema has no field for ("while the battery is charging"). None
 * of that is a gap in authoring — it is the same rule the bionics file states
 * in its own header: a wrong gate is worse than no gate, so a conditional
 * effect is written into `rules` and the quality ladder instead of forced
 * into a `mechanics` entry it does not fit.
 *
 * Where the book prints an unconditional characteristic or armour number —
 * Joint Reconfiguration's +10 Ловкость, Subdermal Armour's +2 AP — it becomes
 * a mechanics entry exactly as in the bionics file.
 *
 * "Interrogate" and other FFG skills with no impmal counterpart (torture,
 * forensic reading of memories) are not forced onto the nearest impmal skill:
 * a wrong skill key is a silent lie on the character sheet. They stay prose.
 *
 * Costs are not printed on these pages (the book's price table lives
 * elsewhere and was not re-derived here); this file follows the same
 * escalation-by-Rarity the bionics file's actual book prices show:
 * R-1 500, R0 800, R1 2000, R2 4000, R3 8000, R4 15000. A judgment call,
 * recorded in the task report.
 */

