/**
 * «Орда» — правила модуля, русский слой.
 *
 * Пак наш собственный и написан по-английски, а русский приходит через Babele —
 * тем же способом, что и переводы платных паков. Так у модуля один
 * распространяемый артефакт на оба языка, и английский стол видит правила
 * ровно так, как они написаны.
 *
 * Заголовки несут те же слаги, что в английском источнике
 * (tools/make-rules.mjs): перевод заголовка без явного `id` убил бы каждую
 * ссылку `@UUID[...#anchor]` в него — см. журнальные файлы основной книги.
 */

export const label = "Правила";

const U = (uuid, label) => `@UUID[${uuid}]{${label}}`;
const h = (level, slug, text) => `<h${level} id="${slug}">${text}</h${level}>`;
const p = (...parts) => `<p>${parts.join("")}</p>`;
const ul = (...items) => `<ul>${items.map(i => `<li><p>${i}</p></li>`).join("")}</ul>`;
const box = (header, ...body) =>
  `<section class="box-text light"><p class="box-header">${header}</p>${body.join("")}</section>`;
const table = (head, rows) =>
  `<table class="impmal"><thead><tr class="subheader">${head.map(c => `<td><p>${c}</p></td>`).join("")}</tr></thead>` +
  `<tbody>${rows.map(r => `<tr>${r.map(c => `<td><p>${c}</p></td>`).join("")}</tr>`).join("")}</tbody></table>`;

const PAGE = id => `.NavisHordePage${id}`;

