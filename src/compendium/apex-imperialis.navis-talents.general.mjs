/** Ids run in the same skill order: Mastery 8–27, Talented 28–47. */
const ORDER = Object.keys(SKILLS);
const id = n => `malExpTal${String(n).padStart(7, "0")}`;

const templated = {};
ORDER.forEach((en, i) => {
  const [nom, gen] = SKILLS[en];
  templated[id(8 + i)] = {
    en: `Mastery (${en})`,
    name: `Мастерство (${nom})`,
    gmNotes: GENERAL,
    requirement: `4 улучшения ${gen}, талант Одарённость (${nom})`,
    description: talent(
      `Очко судьбы: автоматический успех в проверке ${gen}, КУ = бонус характеристики`,
      `Нужны 4 улучшения ${gen} и талант Одарённость (${nom}). Вы можете потратить очко судьбы, чтобы автоматически пройти проверку ${gen}, набрав количество успехов, равное бонусу соответствующей характеристики. `
    )
  };
  templated[id(28 + i)] = {
    en: `Talented (${en})`,
    name: `Одарённость (${nom})`,
    gmNotes: GENERAL,
    requirement: `2 улучшения ${gen}`,
    description: talent(
      `Раз за сессию: переброс проверки ${gen} (берётся лучший результат)`,
      `У вас природная склонность к умению «${nom}». Нужны два улучшения ${gen}. Раз за сессию вы можете перебросить любую проверку ${gen}, даже если результат уже успешен. `
    )
  };
});

