/** Шапка описи: заголовок и названия столбцов. */
const tableHead = (title, ...cols) =>
  `<table class="impmal"><thead><tr class="title"><td colspan="${cols.length}"><p>${title}</p></td></tr>` +
  `<tr class="subheader" style="font-size:20px">${cols.map(c => `<td><p>${c}</p></td>`).join("")}</tr></thead><tbody>`;
